const { spokenNumber } = require('./spoken-number.cjs');
const temporalWord =
  /^(?:на|в|к|ко|с|до|после|через|завтра|сегодня|послезавтра|следующ[а-я]*|ближайш[а-я]*|эт[а-я]*|понедельник[а-я]*|вторник[а-я]*|сред[ауы]|четверг[а-я]*|пятниц[ауы]|суббот[ауы]|воскресень[ея]|январ[а-я]*|феврал[а-я]*|март[а-я]*|апрел[а-я]*|ма[йяею]|июн[а-я]*|июл[а-я]*|август[а-я]*|сентябр[а-я]*|октябр[а-я]*|ноябр[а-я]*|декабр[а-я]*|числ[аоуе]|год[ау]?|час(?:а|ов|у|е|ы|ом|ами|ах)?|полчаса|четверть|минут[а-я]*|утр[а-я]*|дня|днем|вечер[а-я]*|ноч[а-я]*|день|дня|дней|недел[а-я]*|полдень|полночь|позже|позднее|раньше|ранее|то|же|время|оставь|оставьте|прежнее)$/u;
function temporalWordsOnly(value) {
  const text = value.toLowerCase().replace(/ё/gu, 'е');
  return (
    /^[\p{L}\d\s:.,/?!–—-]*$/u.test(text) &&
    [...text.matchAll(/\p{L}+/gu)].every(
      ([word]) =>
        temporalWord.test(word) ||
        spokenNumber(word, 1440) !== null ||
        /^(?:перв|втор|трет|четверт|пят|шест|седьм|восьм|девят|десят|одиннадцат|двенадцат|тринадцат|четырнадцат|пятнадцат|шестнадцат|семнадцат|восемнадцат|девятнадцат|двадцат|тридцат)(?:ое|ого|ый|ой|ую|ая)$/u.test(
          word,
        ),
    )
  );
}
module.exports = { temporalWordsOnly };
