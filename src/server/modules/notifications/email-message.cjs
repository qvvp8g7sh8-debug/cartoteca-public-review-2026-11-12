const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (character) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character],
  );
function emailMessage(
  url,
  { kind = 'reset', organizationName = '', roleName = '', message = '', requestId = '' } = {},
) {
  if (kind === 'notification-test')
    return {
      subject: 'Проверка уведомлений · Картотека',
      text: 'Это пробное письмо из Картотеки. Отправка почтовых уведомлений работает. Если письмо попало в спам, отметьте его как обычное.',
    };
  if (kind === 'support-reply')
    return {
      subject: 'Ответ поддержки · Картотека · ' + requestId.slice(0, 8),
      text:
        'Ответ по обращению № ' +
        requestId +
        '\n\n' +
        message +
        '\n\nОтвет также сохранён в Картотеке. Не сообщайте пароли и данные клиентов.',
    };
  if (kind === 'email-change-old' || kind === 'email-change-new')
    return {
      subject: 'Изменение адреса для входа · Картотека',
      text: message,
    };
  if (kind === 'email-recovery')
    return {
      subject: 'Подтвердите новый адрес для входа · Картотека',
      text:
        'Поддержка подготовила изменение адреса вашего аккаунта. Подтвердите новую почту в течение 30 минут:\n' +
        url +
        '\n\nДо подтверждения прежний адрес и сеансы не изменяются. Если вы не обращались за восстановлением, не открывайте ссылку и свяжитесь с поддержкой.',
    };
  if (kind === 'invitation') {
    const title = 'Приглашение в организацию';
    const text =
      `Вас пригласили в «${organizationName}» в роли «${roleName}».\n\n` +
      `Примите приглашение в течение 7 дней:\n${url}\n\n` +
      'Если вы ещё не зарегистрированы в Картотеке, укажите имя и придумайте пароль. ' +
      'Если аккаунт уже есть, используйте прежний пароль. Доступ к организации появится только после принятия.\n\n' +
      'Если приглашение вам не предназначено, ничего делать не нужно. Не передавайте ссылку другим людям.';
    const html =
      `<div style="font:16px/1.5 Arial,sans-serif;color:#193b50;max-width:560px">` +
      `<h2>${title}</h2><p>Вас пригласили в <strong>${escape(organizationName)}</strong>.</p>` +
      `<p>Ваша роль: <strong>${escape(roleName)}</strong>.</p>` +
      `<p><a href="${escape(url)}" style="display:inline-block;padding:12px 20px;border-radius:8px;background:#234b60;color:#fff;text-decoration:none">Принять приглашение</a></p>` +
      `<p>Ссылка действует 7 дней. Для нового аккаунта укажите имя и придумайте пароль. ` +
      `Для существующего — введите прежний пароль.</p>` +
      `<p>Доступ появится только после принятия. Если приглашение вам не предназначено, проигнорируйте письмо. Не передавайте ссылку.</p></div>`;
    return { subject: title + ' · Картотека', text, html };
  }
  return {
    subject:
      kind === 'verify'
        ? 'Подтверждение регистрации в картотеке'
        : 'Восстановление доступа к картотеке',
    text:
      kind === 'verify'
        ? `Для подтверждения регистрации откройте ссылку в течение суток:\n${url}\n\nЕсли вы не регистрировались, ничего делать не нужно.`
        : `Для установки нового пароля откройте ссылку в течение 15 минут:\n${url}\n\nЕсли вы не запрашивали восстановление, ничего делать не нужно. Не передавайте ссылку другим людям.`,
  };
}
module.exports = { emailMessage };
