test('finite client reads preserve the whole literal identity and the established card/search distinction', () => {
  for (const [text, intent, query] of [
    ['Найди клиента Анну Семёнову', 'clients', 'Анну Семёнову'],
    ['Найдите мне клиентку Алёну Новикову.', 'clients', 'Алёну Новикову'],
    ['Найти клиента Анну-Марию О’Коннор', 'clients', 'Анну-Марию О’Коннор'],
    ['Пожалуйста, найди клиента Сашу Олеговича Иванова', 'clients', 'Сашу Олеговича Иванова'],
    ['Покажи список клиентов Семёновой', 'clients', 'Семёновой'],
    ['Открой список клиентов', 'clients', undefined],
    ['Найди клиента', 'clients', undefined],
    ['Открой карточку Семёнова', 'clientCard', 'Семёнова'],
    ['Покажите мне карту клиента Миры.', 'clientCard', 'Миры'],
    ['Найдите карточку Артура Макартычана', 'clientCard', 'Артура Макартычана'],
    ['Покажи клиента Анну Семёнову', 'clientCard', 'Анну Семёнову'],
    ['Открой клиента Артур', 'clientCard', 'Артур'],
    ['Открой карточку Гульнары Мухамедьяновой', 'clientCard', 'Гульнары Мухамедьяновой'],
    ['Найди клиента Анну Долгову', 'clients', 'Анну Долгову'],
    ['Найди клиента Сашу Запискину', 'clients', 'Сашу Запискину'],
    ['Открой карточку José OʼConnor', 'clientCard', 'José OʼConnor'],
    ['Открой карточку Анны\u2011Марии О’Коннор', 'clientCard', 'Анны\u2010Марии О’Коннор'],
    ['Открой карточку Ивановой, пожалуйста!', 'clientCard', 'Ивановой'],
    ['Открой карточку', 'clientCard', undefined],
    ['Открыть карточку Анны Семёновой', 'clientCard', 'Анны Семёновой'],
    ['Пожалуйста, открыть мне карточку Анны-Марии О’Коннор.', 'clientCard', 'Анны-Марии О’Коннор'],
    ['Открыть карту клиента Миры', 'clientCard', 'Миры'],
    ['Открыть карточку', 'clientCard', undefined],
  ])
    assert.deepEqual(clientReadIntent(text), { intent, ...(query ? { query } : {}) }, text);
});

test('full phone identities reuse existing phone validation without turning tails and dates into a full identity', () => {
  for (const prefix of ['Найди клиента ', 'Открой карточку ', 'Открыть карточку ']) {
    const intent = prefix.startsWith('Найди') ? 'clients' : 'clientCard';
    for (const phone of ['+7 (999) 111-22-33', '89991112233', '+1 202 555 0199']) {
      assert.deepEqual(clientReadIntent(prefix + phone), { intent, query: phone });
      assert.deepEqual(clientReadIntent(prefix + 'по телефону ' + phone), { intent, query: phone });
    }
    for (const query of ['2233', '1112233', '+7 999', '+7 999 111 22 33 или +7 999 111 44 55'])
      assert.equal(clientReadIntent(prefix + query), null, prefix + query);
  }
});

