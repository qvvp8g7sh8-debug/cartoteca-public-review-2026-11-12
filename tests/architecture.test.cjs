test('client factories have unique explicit actions and feature events bind once', () => {
  const owners = new Map(),
    factories = new Set();
  for (const item of manifest.factories) {
    assert.ok(!factories.has(item.factory));
    factories.add(item.factory);
    const ast = acorn.parse(read(item.path), { ecmaVersion: 'latest' }),
      factory = ast.body.find(
        (n) => n.type === 'FunctionDeclaration' && n.id.name === item.factory,
      );
    assert.ok(factory, item.path);
    const returned = factory.body.body.findLast((n) => n.type === 'ReturnStatement');
    assert.equal(returned.argument.type, 'ObjectExpression');
    for (const field of returned.argument.properties) {
      assert.equal(field.type, 'Property');
      assert.equal(field.computed, false);
      assert.ok(!owners.has(field.key.name), 'Duplicate ' + field.key.name);
      owners.set(field.key.name, item.path);
    }
  }
  const events = read(manifest.events) + '\n' + read('src/client/core/settings-events.js');
  for (const action of ['bindServiceEvents', 'bindTeamEvents']) {
    assert.equal(events.split('actions.' + action + '();').length - 1, 1);
    assert.match(owners.get(action), /modules\//);
  }
  assert.doesNotMatch(events, /#toggle-service-edit|#invite-member-form|data-member-role/);
});
test('runtime and route documentation consume the same unique registry', () => {
  const { routes, routeGroups } = require('../src/server/application/routes.cjs');
  assert.equal(require('../src/server/application/server.cjs').routes, routes);
  assert.deepEqual(
    routes,
    routeGroups.flatMap((group) => group.routes),
  );
  assert.equal(new Set(routes.map((r) => r.method + ' ' + r.path)).size, routes.length);
  for (const group of routeGroups) {
    assert.ok(fs.existsSync(path.join(root, group.file)));
    for (const route of group.routes) {
      assert.ok(['public', 'organization', 'global', 'session'].includes(route.access), route.path);
      assert.equal(typeof route.handle, 'function');
    }
  }
});
test('generated styles preserve manifest order and every CSS token', () => {
  assert.equal(new Set(manifest.styles).size, manifest.styles.length);
  for (const file of manifest.styles) assert.match(file, /^src\/client\/styles\/[\w-]+\.css$/);
  const body = manifest.styles.map(read).join(''),
    header =
      '/* Generated by npm run build. Edit src/client/styles; order is in manifest.json. */\n',
    expected = header + compactStyles(body);
  assert.equal(readAsset('ui-extra.css').replace(/\r\n/g, '\n'), expected.replace(/\r\n/g, '\n'));
  const semantic = (source) =>
    JSON.parse(
      JSON.stringify(postcss.parse(source).toJSON(), (key, value) =>
        ['raws', 'source', 'inputs', 'lastEach', 'indexes'].includes(key) ? undefined : value,
      ),
    );
  assert.deepEqual(semantic(readAsset('ui-extra.css').slice(header.length)), semantic(body));
});

