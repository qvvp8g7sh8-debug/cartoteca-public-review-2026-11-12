const test = require('node:test');
const assert = require('node:assert/strict');
const {
  availabilityReadIntent,
} = require('../src/server/modules/assistant/actions/availability-read-request.cjs');
const clock = { date: '2026-10-18', hour: 9, minute: 0 };
test('only one whole explicit civil day and full shared duration can bypass a model', () => {
  for (const [text, date, duration] of [
    ['Найди свободные окна завтра на 30 минут', '2026-10-19', 30],
    ['Покажи свободное окно на сегодня на полчаса.', '2026-10-18', 30],
    ['Покажи свободное время завтра на полчаса.', '2026-10-19', 30],
    ['Пожалуйста, найдите мне свободные окна на 2027-10-21 на один час.', '2027-10-21', 60],
    ['Можешь показать свободное окно завтра на 30 минут', null, null],
    ['Найдите свободное окно завтра на тридцать минут?', '2026-10-19', 30],
    ['Найди свободное окно завтра на 30 минут, пожалуйста.', '2026-10-19', 30],
    ['Найди свободное окно завтра на полчасика', '2026-10-19', 30],
    ['Найди свободное окно завтра на 1ч30', '2026-10-19', 90],
    ['Найди свободное окно завтра на 1,5 часа', '2026-10-19', 90],
    ['Покажите свободные окна на 29.02.2028 на полтора часа', '2028-02-29', 90],
    ['Найди свободное окно на 01/02/2027 на четверть часа', '2027-02-01', 15],
    ['Найди свободное окно на 0001-01-01 на 5 минут', '0001-01-01', 5],
    ['Найди свободное окно на 2099-01-05 на 24 часа', '2099-01-05', 1440],
  ]) {
    assert.deepEqual(
      availabilityReadIntent(text, clock),
      date
        ? {
            intent: 'availability',
            date,
            endDate: date,
            duration,
          }
        : null,
      text,
    );
  }
});
test('missing fields, modifiers, ambiguity and invalid bounds preserve model fallback rather than defaults or help', () => {
  for (const text of [
    'Найди свободные окна',
    'Найди свободные окна завтра',
    'Найди свободные окна на 30 минут',
    'Найди свободные окна завтра на 30',
    'Найди свободные окна завтра на 10',
    'Найди свободные окна завтра на тридцать',
    'Найди свободные окна завтра на 7 минут',
    'Найди свободные окна завтра на 0 минут',
    'Найди свободные окна завтра на 1445 минут',
    'Найди свободные окна завтра на -30 минут',
    'Найди свободные окна на 2027-02-29 на 30 минут',
    'Найди свободные окна на 0000-01-01 на 30 минут',
    'Найди свободные окна на 01.02/2028 на 30 минут',
    'Найди свободные окна послезавтра на 30 минут',
    'Найди свободные окна завтра на 30 минут у Анны',
    'Покажи свободное время завтра на 30 минут у Анны',
    'Покажи свободное время завтра на 30 минут и запиши Иванову',
    'Найди свободные окна завтра на 30 минут для чистки',
    'Найди свободные окна завтра на 30 минут в кабинете первом',
    'Найди свободные окна с 2027-10-21 по 2027-10-22 на 30 минут',
    'Найди свободные окна завтра с 10:00 до 11:00 на 30 минут',
    'Найди свободные окна завтра на 30 или 60 минут',
    'Найди свободные окна завтра на 30 минут на 60 минут',
    'Найди свободные окна завтра на 30 минут, если нет клиентов',
    'Если нет клиентов, найди свободные окна завтра на 30 минут',
    'Не найди свободные окна завтра на 30 минут',
    'Не ищи свободные окна завтра на 30 минут',
    'Найди свободные окна завтра на 30 минут и запиши Иванову',
    'Найди свободные окна завтра на 30 минут и открой календарь',
    'Найди клиента Иванову завтра на 30 минут',
  ])
    assert.equal(availabilityReadIntent(text, clock), null, text);
  for (const value of [null, {}, '', 'я'.repeat(4001)])
    assert.equal(availabilityReadIntent(value, clock), null);
  assert.equal(
    availabilityReadIntent('Найди свободное окно завтра на 30 минут', { date: 'invalid' }),
    null,
  );
});
