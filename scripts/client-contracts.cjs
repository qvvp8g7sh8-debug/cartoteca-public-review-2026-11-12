const fs = require('node:fs');
const path = require('node:path');
const acorn = require('acorn');

function walk(node, visitor) {
  if (!node || typeof node !== 'object') return;
  if (node.type) visitor(node);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach((child) => walk(child, visitor));
    else if (value && typeof value === 'object') walk(value, visitor);
  }
}

function analyzeClient(root, manifest) {
  const ast = (file) =>
    acorn.parse(fs.readFileSync(path.join(root, file), 'utf8'), { ecmaVersion: 'latest' });
  const exports = new Map(),
    imports = new Map(),
    calls = [];
  for (const item of manifest.factories) {
    const tree = ast(item.path),
      factory = tree.body.find(
        (node) => node.type === 'FunctionDeclaration' && node.id.name === item.factory,
      );
    const functions = new Map();
    walk(tree, (node) => {
      if (node.type === 'FunctionDeclaration') functions.set(node.id.name, node);
      if (
        node.type === 'VariableDeclarator' &&
        ['ArrowFunctionExpression', 'FunctionExpression'].includes(node.init?.type)
      )
        functions.set(node.id.name, node.init);
    });
    const result = factory.body.body.findLast((node) => node.type === 'ReturnStatement');
    for (const property of result.argument.properties) {
      const name = property.key.name;
      const fn =
        property.value.type === 'Identifier' ? functions.get(property.value.name) : property.value;
      if (!fn?.params)
        throw Error(item.path + ': exported action has no explicit function signature: ' + name);
      const max = fn.params.some((param) => param.type === 'RestElement')
        ? Infinity
        : fn.params.length;
      // Ordinary JavaScript does permit undefined positional values, but omission of a required
      // position is an architecture error. Defaulted parameters remain optional.
      const min = fn.params.reduce(
        (count, param, index) =>
          param.type === 'AssignmentPattern' || param.type === 'RestElement' ? count : index + 1,
        0,
      );
      exports.set(name, { file: item.path, min, max });
    }
  }
  for (const file of [...manifest.factories.map((item) => item.path), manifest.events]) {
    const names = new Set();
    walk(ast(file), (node) => {
      if (node.type !== 'MemberExpression' || node.object.name !== 'actions') return;
      const name = node.computed
        ? node.property.type === 'Literal' && node.property.value
        : node.property.name;
      if (typeof name !== 'string')
        throw Error(file + ': dynamic access to the action registry is forbidden');
      names.add(name);
    });
    walk(ast(file), (node) => {
      if (
        node.type === 'CallExpression' &&
        node.callee.type === 'MemberExpression' &&
        node.callee.object.name === 'actions'
      ) {
        const name = node.callee.computed ? node.callee.property.value : node.callee.property.name;
        calls.push({
          file,
          name,
          count: node.arguments.length,
          spread: node.arguments.some((arg) => arg.type === 'SpreadElement'),
        });
      }
    });
    imports.set(file, [...names].sort());
  }
  return { exports, imports, calls };
}

function checkClientContracts(analysis, manifest) {
  for (const item of manifest.factories) {
    const actual = analysis.imports.get(item.path);
    if (JSON.stringify(item.dependencies) !== JSON.stringify(actual))
      throw Error(item.path + ': explicit dependencies are stale; run npm run contracts:update');
  }
  if (
    JSON.stringify(manifest.eventDependencies) !==
    JSON.stringify(analysis.imports.get(manifest.events))
  )
    throw Error('Event dependencies are stale; run npm run contracts:update');
  for (const call of analysis.calls) {
    const signature = analysis.exports.get(call.name);
    if (!signature) throw Error(call.file + ': missing action ' + call.name);
    if (!call.spread && (call.count < signature.min || call.count > signature.max))
      throw Error(
        `${call.file}: ${call.name} expects ${signature.min}..${signature.max} arguments, received ${call.count}`,
      );
  }
}

if (require.main === module) {
  const root = path.resolve(__dirname, '..'),
    filename = path.join(root, 'src/client/manifest.json');
  const manifest = JSON.parse(fs.readFileSync(filename, 'utf8')),
    analysis = analyzeClient(root, manifest);
  for (const item of manifest.factories) item.dependencies = analysis.imports.get(item.path);
  manifest.eventDependencies = analysis.imports.get(manifest.events);
  fs.writeFileSync(filename, JSON.stringify(manifest, null, 2) + '\n');
  const typed = ['Service', 'Patient', 'Appointment', 'Visit'];
  fs.writeFileSync(
    path.join(root, 'src/client/contracts/ports.d.ts'),
    '// Generated by npm run contracts:update. Do not edit.\nimport type {SavePorts} from "./domain";\n' +
      typed
        .map((kind) => {
          const item = manifest.factories.find(
            (entry) => entry.factory === 'create' + kind + 'Save',
          );
          return `export type ${kind}SavePorts = Pick<SavePorts, ${item.dependencies.map((name) => JSON.stringify(name)).join(' | ')}>;`;
        })
        .join('\n') +
      '\n',
  );
  checkClientContracts(analysis, manifest);
  console.log('Explicit module dependencies and action arities verified.');
}
module.exports = { analyzeClient, checkClientContracts };
