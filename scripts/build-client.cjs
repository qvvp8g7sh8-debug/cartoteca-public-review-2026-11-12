// Validate everything before writing. Unknown files are never removed or silently shipped.
function verifyOutputInventory(outputs, files) {
  if (outputs.size !== files.length || files.some((file) => !outputs.has(file)))
    throw Error('Client output inventory differs from the explicit public asset list.');
}
function verifyOutputPaths(destination, files) {
  const inspect = (target, directory) => {
    let stat;
    try {
      stat = fs.lstatSync(target);
    } catch (error) {
      if (error.code === 'ENOENT') return false;
      throw error;
    }
    if (stat.isSymbolicLink() || (directory ? !stat.isDirectory() : !stat.isFile()))
      throw Error('Unsafe client output path: ' + path.relative(root, target));
    return true;
  };
  // Refuse junctions/symlinks both in output parents and in individual assets.
  if (!inspect(path.dirname(destination), true) || !inspect(destination, true)) return;
  const expected = new Set(files);
  const directories = new Set(
    files.flatMap((file) => {
      const parts = file.split('/');
      return parts.slice(0, -1).map((_, index) => parts.slice(0, index + 1).join('/'));
    }),
  );
  const visit = (directory, prefix = '') => {
    for (const entry of fs.readdirSync(directory)) {
      const relative = prefix + entry,
        target = path.join(directory, entry);
      if (directories.has(relative)) {
        inspect(target, true);
        visit(target, relative + '/');
      } else {
        if (!expected.has(relative)) throw Error('Unknown client output: ' + relative);
        inspect(target, false);
      }
    }
  };
  visit(destination);
}
